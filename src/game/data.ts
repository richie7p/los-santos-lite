export function getDistrictName(x: number, z: number): string {
  if (z < -60 && x < -60) return '羅克福德山麓豪宅區 (Rockford Hills)';
  if (z < -60 && x >= -60 && x <= 60) return '市中心金融特區 (Downtown Pillbox)';
  if (z < -60 && x > 60) return '好麥塢大道 (Vinewood Blvd)';
  if (x < -90 && z >= 60) return '愛麗舍島貨櫃碼頭 (Elysian Island Pier)';
  if (z > 85) return '威斯普奇陽光海灘 (Vespucci Beach)';
  if (x > 65 && z >= -60) return '拉梅薩工業改裝區 (La Mesa Customs)';
  return '洛聖都中央商業大道 (Legion Square)';
}
